#!/usr/bin/env python3
"""Generates src/windows_zones.rs: the Windows time zone of each IANA one,
as Graph takes event times in (SPEC §10.4).

From CLDR's mapping (common/supplemental/windowsZones.xml), every IANA name
of every territory; and, as CLDR keeps some zones by older names
(Asia/Calcutta), tzdb's links (tzdata.zi), so that either name maps.

    python3 windows_zones.py windowsZones.xml tzdata.zi > src/windows_zones.rs
"""

import sys
import xml.etree.ElementTree as ET

cldr, zi = sys.argv[1:]
windows = {}
for zone in ET.parse(cldr).getroot().iter("mapZone"):
    for name in zone.get("type").split():
        assert windows.setdefault(name, zone.get("other")) == zone.get("other"), name

links = [line.split()[1:3] for line in open(zi) if line.startswith("L ")]
for target, alias in links:
    if target in windows and alias not in windows:
        windows[alias] = windows[target]
    elif alias in windows and target not in windows:
        windows[target] = windows[alias]

print("// Generated by windows_zones.py from CLDR's windowsZones.xml and tzdb's")
print("// tzdata.zi; do not edit.")
print()
print("/// Each IANA time zone's Windows one, by IANA name.")
print("pub(crate) const WINDOWS_ZONES: &[(&str, &str)] = &[")
for name in sorted(windows):
    print(f'    ("{name}", "{windows[name]}"),')
print("];")
